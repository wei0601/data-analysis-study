import numpy as np
scores = np.array([85,92,58,76,45,np.nan,88,60,np.nan,95])
print(np.where(np.isnan(scores)))
print(np.sum(np.isnan(scores)))
print(np.nanmean(scores))
print(np.nansum(scores))
print(np.nanmax(scores))
print(np.nanmin(scores))
print(scores[scores >= 60])
print(np.sum(scores[scores >= 60]))
print(np.sort(scores[~np.isnan(scores)]))
clean_scores = np.where(np.isnan(scores),0,scores)
print(clean_scores)
valid_scores = np.sort(scores[~np.isnan(scores)])
normalized_scores = valid_scores - np.mean(valid_scores)
print(normalized_scores)